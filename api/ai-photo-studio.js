function buildPhotographyPrompt(product, styleId = "marble_studio", customDetails = "") {
  const preset = STUDIO_STYLE_PRESETS[styleId] || STUDIO_STYLE_PRESETS.marble_studio;

  return `You are a world-class e-commerce product commercial photographer and art director.
Your goal is to write 4 distinct, hyper-realistic, photorealistic photography prompts for the Flux image generator for the following product:

Product Name: ${product.name}
Category: ${product.category || "General"}
${product.brand ? `Brand: ${product.brand}` : ""}
${product.description ? `Product Description: ${product.description.slice(0, 300)}` : ""}

Studio Style Theme: ${preset.name} - ${preset.directive}
${customDetails ? `Merchant Custom Requests: ${customDetails}` : ""}

Guidelines:
1. Each prompt must describe a realistic commercial studio shot of the EXACT product type in English.
2. Specify camera angle (e.g., eye-level 45-degree angle, macro close-up, front hero shot, overhead flat-lay).
3. Specify lighting (e.g., rim light, soft studio diffuser, golden hour ray).
4. Specify foreground and background textures, surfaces, and podiums.
5. End each prompt with: "commercial product photography, 8k resolution, photorealistic, sharp focus, ray-traced shadows, award winning studio shot".
6. Avoid showing distorted people or text overlays.

Respond ONLY with a valid, parseable JSON array of 4 items with this exact structure:
[
  {
    "scene_title_ar": "عنوان المشهد بالعربي (مثل: لقطة استوديو على قاعدة رخامية)",
    "prompt": "Detailed English prompt for Flux..."
  },
  ...
]`;
}

async function callGeminiForPrompts(prompt, apiKey) {
  let lastError = null;

  for (const model of MODELS_PRIORITY) {
    try {
      const endpoint = `${GEMINI_BASE_URL}/${model}:generateContent?key=${apiKey}`;
      const response = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            responseMimeType: "application/json",
            temperature: 0.8,
          },
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        const errorMsg = data.error?.message || `HTTP ${response.status}`;
        lastError = new Error(errorMsg);
        if (response.status === 503 || response.status === 429) continue;
        throw lastError;
      }

      const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!text) throw new Error("No prompt content generated by Gemini");

      const cleanJson = text
        .replace(/^```json\s*/i, "")
        .replace(/```\s*$/, "")
        .trim();

      const parsed = JSON.parse(cleanJson);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
      throw new Error("Invalid array format from AI");
    } catch (err) {
      lastError = err;
    }
  }

  throw lastError || new Error("Failed to generate studio photo prompts.");
}

function buildStudioImageUrl(promptText, seed) {
  const sanitizedPrompt = promptText.replace(/[^\w\s,.-]/gi, " ").trim();
  const encodedPrompt = encodeURIComponent(sanitizedPrompt);
  // SANA 512x512 is 100% free with no x402 paywall
  return `https://image.pollinations.ai/prompt/${encodedPrompt}?width=512&height=512&model=sana&seed=${seed}&nologo=true`;
}

export async function handlePhotoStudioRequest(body) {
  const { product, style = "marble_studio", customDetails = "", apiKey } = body || {};

  if (!product || !product.name || typeof product.name !== "string") {
    return {
      status: 400,
      json: { success: false, error: "اسم المنتج مطلوب لتوليد صور الاستوديو." },
    };
  }

  const activeKey =
    (apiKey && typeof apiKey === "string" && apiKey.trim()) ||
    process.env.GEMINI_API_KEY ||
    DEFAULT_GEMINI_KEY;

  if (!activeKey) {
    return {
      status: 400,
      json: {
        success: false,
        error: "يرجى توفير مفتاح Google Gemini API للمتابعة.",
      },
    };
  }

  try {
    const metaPrompt = buildPhotographyPrompt(product, style, customDetails);
    const scenes = await callGeminiForPrompts(metaPrompt, activeKey);

    const baseSeed = Math.floor(Math.random() * 900000) + 100000;
    const photos = scenes.slice(0, 4).map((scene, idx) => {
      const seed = baseSeed + idx * 7919;
      const imageUrl = buildStudioImageUrl(scene.prompt, seed);
      return {
        id: `photo-${Date.now()}-${idx}`,
        title: scene.scene_title_ar || `مشهد استوديو ${idx + 1}`,
        prompt: scene.prompt,
        url: imageUrl,
        seed,
        style,
      };
    });

    return {
      status: 200,
      json: {
        success: true,
        data: {
          productName: product.name,
          style,
          photos,
        },
      },
    };
  } catch (error) {
    console.error("AI Photo Studio generation failed:", error);
    return {
      status: 500,
      json: {
        success: false,
        error: error.message || "تعذر توليد صور الاستوديو للمنتج.",
      },
    };
  }
}

